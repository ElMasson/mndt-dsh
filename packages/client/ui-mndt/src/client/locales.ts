/** Substitution values for a message. */
export type MndtValues = Readonly<Record<string, string | number>>

/** @param key - the message. @param values - placeholders to fill. @returns the text. */
export type MndtTranslate = (key: MndtKey, values?: MndtValues) => string

/** @param key - the message. @param values - placeholders to fill. @returns the text, in French (a tool outside the page). */
export function translate(key: MndtKey, values?: MndtValues): string {
  const template: string = fr[key]
  if (values === undefined) return template
  return template.replace(/\{(\w+)\}/g, function (match: string, name: string) {
    const value = values[name]
    return value === undefined ? match : String(value)
  })
}
