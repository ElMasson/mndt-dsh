#!/usr/bin/env node
/**
 * Pin the governance distribution and verify it.
 *
 * The team should run exactly the artifacts that were verified. This script
 * records the package versions and the SHA-256 of every built file that actually
 * ships, then re-checks them. A rebuilt bundle that differs from the pin fails
 * loudly instead of silently reaching a workstation.
 *
 * Usage:
 *   node scripts/distribution.mjs --write   # write or refresh the lock
 *   node scripts/distribution.mjs --check   # verify, exit 1 on drift
 */
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const hostPackage = resolve(here, '..')
const clientPackage = resolve(here, '../../../client/ui-governance')
const lockPath = join(hostPackage, 'distribution.lock.json')

/** Files that must be identical wherever the plugin is installed. */
const artifacts = [
  { package: '@deepseek-ai/dsh-host-governance', path: join(hostPackage, 'lib/index.js') },
  { package: '@deepseek-ai/dsh-host-governance', path: join(hostPackage, 'lib/typert.host.js') },
  { package: '@deepseek-ai/dsh-host-governance', path: join(hostPackage, 'lib/typert.remote-client.js') },
  { package: '@deepseek-ai/dsh-client-ui-governance', path: join(clientPackage, 'lib/index.js') },
  { package: '@deepseek-ai/dsh-client-ui-governance', path: join(clientPackage, 'lib/client.js') },
]

/** @param path - file to hash. @returns its SHA-256, or null when absent. */
function sha256(path) {
  if (!existsSync(path)) return null
  return createHash('sha256').update(readFileSync(path)).digest('hex')
}

/** @param dir - package directory. @returns the package version. */
function version(dir) {
  const manifest = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'))
  return manifest.version
}

/** @returns the distribution pin. */
function buildLock() {
  return {
    note: 'Generated by scripts/distribution.mjs. Verified artifacts of the governed DSH plugin.',
    pinnedAt: new Date().toISOString(),
    versions: {
      '@deepseek-ai/dsh-host-governance': version(hostPackage),
      '@deepseek-ai/dsh-client-ui-governance': version(clientPackage),
    },
    artifacts: artifacts.map(({ package: name, path }) => {
      const normalized = path.replaceAll('\\', '/')
      const at = normalized.indexOf('/packages/')
      return {
        package: name,
        file: at === -1 ? normalized : normalized.slice(at + 1),
        sha256: sha256(path),
      }
    }),
  }
}

const mode = process.argv[2]

if (mode === '--write') {
  const lock = buildLock()
  writeFileSync(lockPath, `${JSON.stringify(lock, null, 2)}\n`, 'utf8')
  const missing = lock.artifacts.filter((entry) => entry.sha256 === null).map((entry) => entry.file)
  process.stdout.write(`wrote ${lockPath}\n`)
  process.stdout.write(`artifacts pinned: ${lock.artifacts.length - missing.length}/${lock.artifacts.length}\n`)
  if (missing.length > 0) process.stdout.write(`MISSING (build first): ${missing.join(', ')}\n`)
  process.exit(missing.length === 0 ? 0 : 1)
}

if (mode === '--check') {
  if (!existsSync(lockPath)) {
    process.stderr.write(`no lock at ${lockPath}; run --write first\n`)
    process.exit(1)
  }
  const lock = JSON.parse(readFileSync(lockPath, 'utf8'))
  const current = buildLock()
  const unhashed = lock.artifacts.filter((entry) => entry.sha256 === null || entry.sha256 === undefined)
  const drift = current.artifacts.filter((entry, index) => entry.sha256 !== lock.artifacts[index]?.sha256)
  const moved = Object.keys(current.versions).filter((name) => current.versions[name] !== lock.versions[name])
  if (drift.length > 0 || moved.length > 0 || unhashed.length > 0) {
    process.stderr.write('distribution drift detected\n')
    for (const entry of unhashed) process.stderr.write(`  never hashed: ${entry.file ?? '(unnamed)'}\n`)
    for (const entry of drift) process.stderr.write(`  changed: ${entry.file}\n`)
    for (const name of moved) process.stderr.write(`  version moved: ${name}\n`)
    process.exit(1)
  }
  process.stdout.write(`distribution verified: ${current.artifacts.length} artifacts, no drift\n`)
  process.exit(0)
}

process.stderr.write('usage: node scripts/distribution.mjs --write|--check\n')
process.exit(2)
